function latinToCyrillic(value) {
  const pairs = [
    ["O‘", "Ў"],
    ["O'", "Ў"],
    ["o‘", "ў"],
    ["o'", "ў"],
    ["G‘", "Ғ"],
    ["G'", "Ғ"],
    ["g‘", "ғ"],
    ["g'", "ғ"],
    ["SH", "Ш"],
    ["Sh", "Ш"],
    ["sh", "ш"],
    ["CH", "Ч"],
    ["Ch", "Ч"],
    ["ch", "ч"],
    ["YO", "Ё"],
    ["Yo", "Ё"],
    ["yo", "ё"],
    ["YU", "Ю"],
    ["Yu", "Ю"],
    ["yu", "ю"],
    ["YA", "Я"],
    ["Ya", "Я"],
    ["ya", "я"],
    ["NG", "НГ"],
    ["Ng", "Нг"],
    ["ng", "нг"],
  ];
  let result = value;
  pairs.forEach(([from, to]) => {
    result = result.replaceAll(from, to);
  });
  const letters = {
    A: "А",
    B: "Б",
    D: "Д",
    E: "Е",
    F: "Ф",
    G: "Г",
    H: "Ҳ",
    I: "И",
    J: "Ж",
    K: "К",
    L: "Л",
    M: "М",
    N: "Н",
    O: "О",
    P: "П",
    Q: "Қ",
    R: "Р",
    S: "С",
    T: "Т",
    U: "У",
    V: "В",
    X: "Х",
    Y: "Й",
    Z: "З",
    a: "а",
    b: "б",
    d: "д",
    e: "е",
    f: "ф",
    g: "г",
    h: "ҳ",
    i: "и",
    j: "ж",
    k: "к",
    l: "л",
    m: "м",
    n: "н",
    o: "о",
    p: "п",
    q: "қ",
    r: "р",
    s: "с",
    t: "т",
    u: "у",
    v: "в",
    x: "х",
    y: "й",
    z: "з",
  };
  return [...result].map((char) => letters[char] || char).join("");
}

export function createTranslator(language = "ru") {
  const dictionary = dictionaries[language] || {};
  return (text, values = {}) => {
    let result =
      dictionary[text] ||
      (language === "uz-cyrl" && uz[text] ? latinToCyrillic(uz[text]) : text);
    Object.entries(values).forEach(([key, value]) => {
      result = result.replaceAll(`{${key}}`, String(value));
    });
    return result;
  };
}
