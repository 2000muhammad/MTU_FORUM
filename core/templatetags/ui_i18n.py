def _lang(context=None):
    request = context.get("request") if context else None
    path = getattr(request, "path", "") or ""
    for code, _ in sorted(settings.LANGUAGES, key=lambda item: len(item[0]), reverse=True):
        if path == f"/{code}" or path.startswith(f"/{code}/"):
            return code if code in UI else code.split("-")[0]
    language = (get_language() or "ru").lower()
    return language if language in UI else language.split("-")[0] if language.split("-")[0] in UI else "ru"


@register.simple_tag(takes_context=True)
def tr(context, key):
    language = _lang(context)
    return UI.get(language, UI["ru"]).get(key, UI["ru"].get(key, key))


@register.simple_tag(takes_context=True)
def lang_url(context, code):
    request = context.get("request")
    path = getattr(request, "path", "/") or "/"
    prefixes = [f"/{lang}/" for lang, _ in sorted(settings.LANGUAGES, key=lambda item: len(item[0]), reverse=True)]
    stripped = path
    for prefix in prefixes:
        if path == prefix[:-1]:
            stripped = "/"
            break
        if path.startswith(prefix):
            stripped = "/" + path[len(prefix):]
            break
    return f"/{code}{stripped}"
